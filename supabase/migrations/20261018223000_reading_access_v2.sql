-- V2 foundation only: this migration does not modify legacy books/notes/members.
-- Review and test against a disposable Supabase instance before production use.
-- Uses Supabase auth.uid() and PostgreSQL 14+ gen_random_uuid().
--
-- Security boundary: authenticated users get limited table privileges;
-- room/member creation and membership rules are controlled by SECURITY DEFINER RPC.
-- This is NOT a substitute for protected book-content delivery, invitation,
-- blocking, archival/audit guarantees, or server-side rate limiting.

CREATE TABLE public.reading_rooms_v2 (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  owner_id uuid NOT NULL REFERENCES auth.users(id),
  title text NOT NULL CHECK (char_length(btrim(title)) BETWEEN 1 AND 200),
  state text NOT NULL DEFAULT 'active' CHECK (state IN ('active','archived','closed')),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.reading_members_v2 (
  room_id uuid NOT NULL REFERENCES public.reading_rooms_v2(id) ON DELETE CASCADE,
  user_id uuid NOT NULL REFERENCES auth.users(id),
  role text NOT NULL CHECK (role IN ('owner','partner')),
  joined_at timestamptz NOT NULL DEFAULT now(),
  left_at timestamptz,
  PRIMARY KEY (room_id,user_id),
  -- Exactly one owner slot and one partner slot; never a third member.
  UNIQUE (room_id,role)
);

CREATE INDEX reading_members_v2_active_lookup
  ON public.reading_members_v2 (user_id,room_id)
  WHERE left_at IS NULL;

CREATE TABLE public.reading_notes_v2 (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  room_id uuid NOT NULL,
  author_id uuid NOT NULL,
  start_offset integer NOT NULL CHECK (start_offset >= 0),
  end_offset integer NOT NULL CHECK (end_offset > start_offset),
  body text NOT NULL CHECK (char_length(body) BETWEEN 1 AND 10000),
  visibility text NOT NULL DEFAULT 'private' CHECK (visibility IN ('private','shared')),
  revision bigint NOT NULL DEFAULT 1 CHECK (revision > 0),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  FOREIGN KEY (room_id,author_id)
    REFERENCES public.reading_members_v2(room_id,user_id)
);

CREATE INDEX reading_notes_v2_room_lookup
  ON public.reading_notes_v2 (room_id,created_at,id);
CREATE INDEX reading_notes_v2_author_lookup
  ON public.reading_notes_v2 (author_id,created_at,id);

ALTER TABLE public.reading_rooms_v2 ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.reading_members_v2 ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.reading_notes_v2 ENABLE ROW LEVEL SECURITY;

-- The definer can inspect memberships without recursively invoking their RLS
-- policies. No dynamic SQL, request-controlled search_path, or client-supplied
-- user id is trusted.
CREATE FUNCTION public.v2_is_room_member(room uuid)
RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.reading_members_v2 m
    WHERE m.room_id = room
      AND m.user_id = (SELECT auth.uid())
      AND m.left_at IS NULL
  );
$$;

CREATE FUNCTION public.v2_can_edit_room(room uuid)
RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.reading_rooms_v2 r
    JOIN public.reading_members_v2 m ON m.room_id = r.id
    WHERE r.id = room
      AND r.state = 'active'
      AND m.user_id = (SELECT auth.uid())
      AND m.left_at IS NULL
  );
$$;

-- Trusted RPC handles both inserts atomically. Direct client writes to
-- room/member tables are denied by the absence of INSERT/UPDATE/DELETE grants.
CREATE FUNCTION public.v2_create_reading_room(book_title text)
RETURNS uuid
LANGUAGE plpgsql VOLATILE SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  actor uuid := auth.uid();
  room uuid;
BEGIN
  IF actor IS NULL THEN
    RAISE EXCEPTION 'Authentication required' USING ERRCODE = '28000';
  END IF;
  IF book_title IS NULL OR char_length(pg_catalog.btrim(book_title)) NOT BETWEEN 1 AND 200 THEN
    RAISE EXCEPTION 'Invalid book title' USING ERRCODE = '22023';
  END IF;

  INSERT INTO public.reading_rooms_v2 (owner_id,title)
  VALUES (actor, pg_catalog.btrim(book_title))
  RETURNING id INTO room;

  INSERT INTO public.reading_members_v2 (room_id,user_id,role)
  VALUES (room,actor,'owner');

  RETURN room;
END;
$$;

-- Prevent manipulating record provenance, author, or revision counters through
-- a permitted UPDATE; timestamp and revision are generated by the database.
CREATE FUNCTION public.v2_guard_note_update()
RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  IF NEW.room_id IS DISTINCT FROM OLD.room_id
     OR NEW.author_id IS DISTINCT FROM OLD.author_id
     OR NEW.id IS DISTINCT FROM OLD.id
     OR NEW.created_at IS DISTINCT FROM OLD.created_at THEN
    RAISE EXCEPTION 'Note identity and provenance cannot be changed'
      USING ERRCODE = '23514';
  END IF;
  NEW.revision := OLD.revision + 1;
  NEW.updated_at := now();
  RETURN NEW;
END;
$$;
CREATE TRIGGER reading_notes_v2_guard_update
BEFORE UPDATE ON public.reading_notes_v2
FOR EACH ROW EXECUTE FUNCTION public.v2_guard_note_update();

-- Prevent client-provided fake revision / timestamps on INSERT as well.
CREATE FUNCTION public.v2_guard_note_insert()
RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  NEW.revision := 1;
  NEW.created_at := now();
  NEW.updated_at := NEW.created_at;
  RETURN NEW;
END;
$$;
CREATE TRIGGER reading_notes_v2_guard_insert
BEFORE INSERT ON public.reading_notes_v2
FOR EACH ROW EXECUTE FUNCTION public.v2_guard_note_insert();

CREATE POLICY reading_rooms_v2_read
ON public.reading_rooms_v2 FOR SELECT TO authenticated
USING (
  owner_id = (SELECT auth.uid())
  OR public.v2_is_room_member(id)
);

CREATE POLICY reading_members_v2_read
ON public.reading_members_v2 FOR SELECT TO authenticated
USING (
  user_id = (SELECT auth.uid())
  OR public.v2_is_room_member(room_id)
);

CREATE POLICY reading_notes_v2_read
ON public.reading_notes_v2 FOR SELECT TO authenticated
USING (
  author_id = (SELECT auth.uid())
  OR (visibility = 'shared' AND public.v2_is_room_member(room_id))
);

CREATE POLICY reading_notes_v2_insert
ON public.reading_notes_v2 FOR INSERT TO authenticated
WITH CHECK (
  author_id = (SELECT auth.uid())
  AND public.v2_can_edit_room(room_id)
);

CREATE POLICY reading_notes_v2_update
ON public.reading_notes_v2 FOR UPDATE TO authenticated
USING (
  author_id = (SELECT auth.uid())
  AND public.v2_can_edit_room(room_id)
)
WITH CHECK (
  author_id = (SELECT auth.uid())
  AND public.v2_can_edit_room(room_id)
);

-- Deletion/erasure and shared memorial archives require a separate, audited
-- workflow. No direct DELETE grant is exposed in this initial migration.

REVOKE ALL ON public.reading_rooms_v2 FROM PUBLIC,anon,authenticated;
REVOKE ALL ON public.reading_members_v2 FROM PUBLIC,anon,authenticated;
REVOKE ALL ON public.reading_notes_v2 FROM PUBLIC,anon,authenticated;
GRANT SELECT ON public.reading_rooms_v2 TO authenticated;
GRANT SELECT ON public.reading_members_v2 TO authenticated;
GRANT SELECT,INSERT,UPDATE ON public.reading_notes_v2 TO authenticated;

REVOKE ALL ON FUNCTION public.v2_is_room_member(uuid) FROM PUBLIC,anon,authenticated;
REVOKE ALL ON FUNCTION public.v2_can_edit_room(uuid) FROM PUBLIC,anon,authenticated;
REVOKE ALL ON FUNCTION public.v2_create_reading_room(text) FROM PUBLIC,anon,authenticated;
REVOKE ALL ON FUNCTION public.v2_guard_note_update() FROM PUBLIC,anon,authenticated;
REVOKE ALL ON FUNCTION public.v2_guard_note_insert() FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.v2_is_room_member(uuid) TO authenticated;
GRANT EXECUTE ON FUNCTION public.v2_can_edit_room(uuid) TO authenticated;
GRANT EXECUTE ON FUNCTION public.v2_create_reading_room(text) TO authenticated;
